import { createHmac } from "node:crypto";
import { readFile } from "node:fs/promises";
import { PrismaClient } from "@prisma/client";
const db = new PrismaClient();

const base = "http://127.0.0.1:3000";
const phone = "15500001234";
const secret = process.env.SESSION_SECRET;
const user = await db.user.findUniqueOrThrow({ where: { phone } });
const cookie = `emotional_map_session=${user.id}.${createHmac("sha256", secret).update(user.id).digest("base64url")}`;
const headers = { Cookie: cookie };
const image = await readFile("/private/tmp/emotional-map-test.png");
const form = new FormData(); form.set("photo", new Blob([image], { type: "image/png" }), "test.png");
const upload = await fetch(`${base}/api/uploads`, { method: "POST", headers, body: form });
if (!upload.ok) throw new Error(`Upload failed: ${await upload.text()}`);
const uploaded = await upload.json();
const emotions = await (await fetch(`${base}/api/emotions`)).json();
const picks = ["Freedom", "Peace", "Wonder"].map((name, index) => ({ emotionId: emotions.find((emotion) => emotion.canonicalName === name).id, intensity: [9, 7, 5][index], customExpression: index === 0 ? "Finally outside" : "" }));
const input = { photoUrl: uploaded.photoUrl, photoMetadata: uploaded.metadata, location: { placeName: "Hyde Park", city: "London", country: "United Kingdom" }, capturedAt: "2025-10-21", emotions: picks, story: "A verified local memory.", visibility: "PRIVATE" };
const created = await fetch(`${base}/api/memories`, { method: "POST", headers: { ...headers, "content-type": "application/json" }, body: JSON.stringify(input) });
if (!created.ok) throw new Error(`Create failed: ${await created.text()}`);
const { id } = await created.json();
const stored = await db.memory.findUniqueOrThrow({ where: { id }, include: { location: true, emotions: true } });
if (stored.emotions.length !== 3 || stored.location.latitude === null) throw new Error("Stored memory did not preserve feelings or development map coordinate.");
const updated = await fetch(`${base}/api/memories/${id}`, { method: "PUT", headers: { ...headers, "content-type": "application/json" }, body: JSON.stringify({ ...input, story: "An edited, verified local memory." }) });
if (!updated.ok) throw new Error(`Update failed: ${await updated.text()}`);
const detail = await fetch(`${base}/memories/${id}`, { headers }); if (!detail.ok || !(await detail.text()).includes("An edited, verified local memory.")) throw new Error("Detail route did not render saved data.");
const deleted = await fetch(`${base}/api/memories/${id}`, { method: "DELETE", headers }); if (!deleted.ok) throw new Error(`Delete failed: ${await deleted.text()}`);
if (await db.memory.findUnique({ where: { id } })) throw new Error("Delete did not remove the SQLite record.");
console.log("Phase 1 API smoke test passed: upload → create → map-ready coordinate → detail → update → delete.");
await db.$disconnect();
